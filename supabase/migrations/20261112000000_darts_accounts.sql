-- Darts AutoScore: accounts, game history and stats. Everything is owner-only via RLS.

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null unique check (username ~ '^[a-z0-9_]{3,16}$'),
  created_at timestamptz not null default now()
);

create table public.games (
  id uuid primary key,                       -- generated by the app => idempotent uploads
  user_id uuid not null references public.profiles (id) on delete cascade,
  played_at timestamptz not null,
  start_score int not null check (start_score in (301, 501)),
  double_out boolean not null,
  players jsonb not null,
  winner int,
  turns jsonb not null,
  my_won boolean not null,
  my_points int not null check (my_points >= 0),
  my_turns int not null check (my_turns >= 0),
  my_highest int not null check (my_highest between 0 and 180),
  my_100 int not null default 0,
  my_140 int not null default 0,
  my_180 int not null default 0,
  my_busts int not null default 0,
  my_best_finish int check (my_best_finish between 2 and 170),
  created_at timestamptz not null default now()
);
create index games_user_played_idx on public.games (user_id, played_at desc);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, username)
  values (new.id, lower(new.raw_user_meta_data ->> 'username'));
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users for each row execute function public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.games enable row level security;

create policy profiles_select_own on public.profiles for select to authenticated using (id = (select auth.uid()));
create policy games_select_own on public.games for select to authenticated using (user_id = (select auth.uid()));
create policy games_insert_own on public.games for insert to authenticated with check (user_id = (select auth.uid()));
create policy games_update_own on public.games for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy games_delete_own on public.games for delete to authenticated using (user_id = (select auth.uid()));

revoke all on public.profiles, public.games from anon, authenticated;
grant select on public.profiles to authenticated;
grant select, insert, update, delete on public.games to authenticated;

-- In-app account deletion (required by Apple/Google for apps with sign-up). Cascades to profile and games.
create or replace function public.delete_my_account()
returns void language plpgsql security definer set search_path = '' as $$
begin
  if (select auth.uid()) is null then raise exception 'not authenticated'; end if;
  delete from auth.users where id = (select auth.uid());
end $$;

revoke execute on all functions in schema public from public, anon;
revoke execute on function public.handle_new_user() from authenticated;
grant execute on function public.delete_my_account() to authenticated;
